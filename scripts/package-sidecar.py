#!/usr/bin/env python3
"""Package the Python sidecar into the mod's resources.

Everything under ``sidecar/`` (excluding virtualenvs, caches and bytecode) is copied to
``src/main/resources/assets/malanguagelearning/sidecar/`` and a manifest listing every
copied file is written next to it. At runtime the Java provisioner reads that manifest
and unpacks the files into the user's config directory, which is how the mod ships a
working speech engine without the user installing anything.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "sidecar"
RESOURCES = ROOT / "src" / "main" / "resources" / "assets" / "malanguagelearning"
TARGET = RESOURCES / "sidecar"
MANIFEST = ROOT / "src" / "main" / "resources" / "sidecar-manifest.txt"

SKIP_DIRS = {
    "__pycache__",
    ".venv",
    "venv",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    "node_modules",
    ".git",
}
SKIP_SUFFIXES = {".pyc", ".pyo", ".so", ".dylib", ".pyd"}


def wanted(path: Path) -> bool:
    if any(part in SKIP_DIRS for part in path.parts):
        return False
    if path.suffix.lower() in SKIP_SUFFIXES:
        return False
    if path.name in {".DS_Store", "Thumbs.db"}:
        return False
    return True


def main() -> int:
    if not SOURCE.is_dir():
        print(f"error: {SOURCE} does not exist", file=sys.stderr)
        return 1

    if TARGET.exists():
        shutil.rmtree(TARGET)
    TARGET.mkdir(parents=True, exist_ok=True)

    entries: list[str] = []
    for path in sorted(SOURCE.rglob("*")):
        if not path.is_file() or not wanted(path.relative_to(SOURCE)):
            continue
        relative = path.relative_to(SOURCE)
        destination = TARGET / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, destination)
        entries.append(relative.as_posix())

    if not entries:
        print("error: sidecar/ is empty — nothing to package", file=sys.stderr)
        return 1

    MANIFEST.write_text(
        "# Generated by scripts/package-sidecar.py — do not edit by hand.\n"
        "# Relative paths of every file the mod unpacks from the jar.\n"
        + "\n".join(entries)
        + "\n",
        encoding="utf-8",
    )

    print(f"packaged {len(entries)} sidecar files into {TARGET.relative_to(ROOT)}")
    print(f"manifest: {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
